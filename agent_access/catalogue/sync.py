"""Fill the catalogue's implementation fields from the rule registry (agent_access/rules).

    python -m agent_access.catalogue.sync          # rewrite agent_access/catalogue/wcag_2_2_rules.json
    python -m agent_access.catalogue.sync --check  # exit 1 if the file is out of date (tests run this)

Generated from the code every time: implementation_status, detection_method, and automated_checks (the rule's
name, technologies, and probes). manual_checks is what an agent (and a human tester) must judge for every criterion:
for a judgement rule, what automation can't decide; for a measured rule, how to confirm the measurement covered the
page. It is seeded from the rule's docstring only while it is empty, so edits made in the JSON are kept. Agents read
it through get_criterion and run_rule's your_judgement_needed.
"""

from __future__ import annotations

import argparse
import json
import sys

from agent_access.catalogue.catalogue import CATALOGUE_PATH

NOTES = [
    "This catalogue contains every active WCAG 2.2 success criterion. Each one has an automated rule "
    "(agent_access/rules, listed in automated_checks) and manual_checks: what an agent or human tester must judge, "
    "or, for a measured rule (detection_method automated), how to confirm the measurement covered the page.",
    "The AA target includes A and AA criteria. AAA criteria remain in the catalogue with in_target_scope=false.",
    "implementation_status, detection_method, and automated_checks are generated by python -m agent_access.catalogue.sync. "
    "manual_checks is seeded from the rule's docstring once and can then be edited here.",
    "Do not treat an unimplemented or unassessed criterion as passing.",
    "Full conformance also requires evaluating WCAG conformance requirements, full pages, and complete processes.",
]


def synced(data: dict) -> dict:
    from agent_access.rules import REGISTRY

    for principle in data["principles"]:
        for guideline in principle["guidelines"]:
            for raw in guideline["rules"]:
                tool = REGISTRY[raw["wcag_criterion"]]
                raw["implementation_status"] = "implemented"
                raw["detection_method"] = "automated_and_agent_judgement" if tool.judgement else "automated"
                raw["automated_checks"] = [{"check": tool.name, "technologies": list(tool.tech), "probes": list(tool.uses)}]
                if not raw["manual_checks"]:
                    raw["manual_checks"] = [tool.doc]
    data["notes"] = NOTES
    data["catalogue_status"] = "complete_success_criteria_catalogue_with_rules"
    return data


def render(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only report whether the file is up to date")
    args = parser.parse_args(argv)
    current = CATALOGUE_PATH.read_text(encoding="utf-8")
    updated = render(synced(json.loads(current)))
    if args.check:
        if updated != current:
            print(f"{CATALOGUE_PATH} is out of date: run python -m agent_access.catalogue.sync", file=sys.stderr)
            return 1
        return 0
    CATALOGUE_PATH.write_text(updated, encoding="utf-8")
    print(f"Updated {CATALOGUE_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
