"""Loader for the WCAG 2.2 rules catalogue (agent_access/catalogue/wcag_2_2_rules.json).

Only the fields the code reads are loaded. The JSON also carries reference data (principle, guideline,
source_url) and fields generated by agent_access/catalogue/sync.py (implementation_status, automated_checks, ...).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

CATALOGUE_PATH = Path(__file__).with_name("wcag_2_2_rules.json")

LEVEL_ORDER = {"A": 1, "AA": 2, "AAA": 3}


@dataclass(frozen=True)
class Rule:
    rule_id: str
    wcag_criterion: str
    title: str
    level: str
    understanding_url: str
    manual_checks: tuple[str, ...]  # what an agent (or a human tester) must judge


@dataclass(frozen=True)
class Catalogue:
    rules: tuple[Rule, ...]
    removed_criteria: frozenset[str]

    def get(self, criterion: str) -> Rule | None:
        """Look up a rule by criterion number ("1.1.1") or rule_id ("WCAG_1_1_1")."""
        key = criterion.strip()
        return next((r for r in self.rules if key in (r.wcag_criterion, r.rule_id)), None)

    def up_to_level(self, level: str) -> list[Rule]:
        return [r for r in self.rules if LEVEL_ORDER[r.level] <= LEVEL_ORDER[level]]


@lru_cache(maxsize=1)
def load_catalogue(path: Path = CATALOGUE_PATH) -> Catalogue:
    data = json.loads(path.read_text(encoding="utf-8"))
    rules = tuple(
        Rule(raw["rule_id"], raw["wcag_criterion"], raw["title"], raw["level"], raw["understanding_url"],
             tuple(raw["manual_checks"]))
        for principle in data["principles"] for guideline in principle["guidelines"] for raw in guideline["rules"]
    )
    return Catalogue(rules, frozenset(c["wcag_criterion"] for c in data.get("removed_criteria", [])))
